    #[test]
    fn a_loaded_snapshot_restarts_the_idle_clock() {
        let snapshot = {
            let mut hub = TestHub::<ArenaHub>::spawn_with("arena", "pit", br#"{"idle_ms":1000,"spawns":[[10,10],[11,10]]}"#).unwrap();
            let _: bool = hub.call_typed(Caller::Player(1), "join", &json!({ "class": "warrior" })).unwrap();
            let _: bool = hub.call_typed(Caller::Player(2), "join", &json!({ "class": "mage" })).unwrap();
            let _: bool = hub.call_typed(Caller::Player(1), "start", &()).unwrap();
            hub.hub_mut().arena.fighters.iter_mut().for_each(|f| f.moved_at = 0);
            hub.persist().unwrap()
        };
        let mut hub = TestHub::<ArenaHub>::load("arena", "pit", &snapshot, 1).unwrap();
        let now = hub.now_ms();
        assert!(hub.hub().arena.fighters.iter().all(|f| f.moved_at == now));
        assert!(hub.hub_mut().arena.tick(now + 100));
        assert_eq!(hub.hub().arena.fighters.len(), 2);
    }
