//! An arena, keyed by its id: players fight in real time with the abilities of the class they
//! pick, and the hub referees every hit. The shape of a brawler, an arena shooter, a skirmish:
//! clients report where their player is (`move { x, y }`, a few times a second) and the movement
//! warden keeps what the class's speed allows; a cast is checked for its cooldown, resource and
//! range (`ckx_sdk::kit::play::abilities`) and lands as the hub decides: a hit-scan strike on the
//! fighter nearest its aim, a projectile the hub flies a tick at a time, an area that goes off
//! after its delay; statuses tick (`ckx_sdk::kit::play::combat`); the fallen come back after
//! `respawn_ms`; the first to `kill_target` kills, or the most kills when the time runs out, wins.
//! Replace the [`Config`]'s classes with your game's.
//!
//! This is the Unreal SDK's z-up copy of the platform's starter. What differs: every position,
//! on the wire and in the view, is in world metres on the ground, `x` then `y` (the Unreal
//! location over 100), the arena is the rectangle from `origin` of `width` along X and `depth`
//! along Y, and `spawns` are offsets from the origin. With `realtime` on, casts, impacts and the
//! warden's flags also go out as realtime events (94 and 95) at the arena's centre chunk
//! (16 m chunks, z up, `height` metres up). And five holes are closed. A `move` or `cast` whose
//! position is not a finite number is refused `bad_request` and spends nothing. A fighter who
//! leaves a running fight is benched with their record (class, health, kills, deaths, cooldowns,
//! resource, respawn) and `join` brings them back as they were; a different class is `started`,
//! and a new player may still join. A fighter who leaves stays in the arena for `respawn_ms`:
//! projectiles, areas and burning reach them where they stood and a kill leaves them down when
//! they rejoin, so leaving and coming back does not dodge a hit. After that, and from the first
//! moment for one benched as idle or removed, they are no target. At most `players_max` times 4
//! are benched (the oldest not removed go first). The platform's warden gives every
//! report 0.5 m of slack, so a client reporting faster moved faster; this crate's own warden
//! gives each fighter a travel budget that grows with the time since the last report at the
//! class's speed (times the grace) and holds at most 1 s of it plus 0.5 m, so the rate buys no
//! speed. A cut of 1 m or less is jitter and a bounds clamp is not a violation: neither is a
//! strike. A fighter the hub has just placed (join, start, respawn, rejoin) is answered with the
//! place, with no strike, until a report comes from within reach of it. An instant ability also
//! needs its victim within its range of the caster, not only the aim point. A fighter removed
//! for movement is benched as removed: their `join` is `forbidden` until the next `start`. A running
//! fighter who is up and sends no `move` for `idle_ms` is benched by the tick with `removed`
//! (`why`: `idle`), and may rejoin as they were; 0 never does. The view shows `resource` as it
//! has regenerated by now. A snapshot from the platform's arena loads: its positions are the
//! same numbers with the origin at `[0, 0]`.
//!
//! Endpoints (players): `join { class }`, `start` (the first to join, or a developer), `move
//! { x, y }` (answers the position kept, as `{ x, y }`), `cast { ability, x, y }` (aimed at a point), `leave`,
//! `state` (anyone). It speaks the kit protocol (`ckx_sdk::kit`): the `arena` topic carries the
//! fighters (health, resource, statuses, kills, positions), projectiles and pending areas as
//! `snapshot` messages up to five times a second, and `event` messages (`type`: `cast`,
//! `impact`, `kill`, `respawn`, `violation`, `removed`, `finished`) as they happen;
//! `snapshot { topic: "arena" }` answers it; changes may carry an `action_id`; refusals carry
//! `kit:<code>:` codes.

