fn dist(a: (f64, f64), b: (f64, f64)) -> f64 {
    ((a.0 - b.0).powi(2) + (a.1 - b.1).powi(2)).sqrt()
}

/// Whether both numbers are finite, also as the `f32`s the ability book works in.
fn finite(p: (f64, f64)) -> bool {
    (p.0 as f32).is_finite() && (p.1 as f32).is_finite()
}

/// The resource a book holds at `now`, as `CasterBook::regen` would leave it, without changing it.
fn resource_at(book: &CasterBook, now: u64) -> i64 {
    if book.last_regen_ms == 0 {
        return book.resource;
    }
    let gained = (now.saturating_sub(book.last_regen_ms) as i64 * book.regen_per_sec) / 1000;
    if gained > 0 { (book.resource + gained).min(book.resource_max) } else { book.resource }
}

impl Arena {
    pub fn view(&self, now: u64) -> ArenaView {
        ArenaView {
            phase: self.phase,
            origin: self.config.origin,
            width: self.config.width,
            depth: self.config.depth,
            fighters: self
                .fighters
                .iter()
                .map(|f| {
                    let (x, y) = f.at();
                    FighterView {
                        player: f.player,
                        class: f.class.clone(),
                        x,
                        y,
                        hp: f.combatant.health.current,
                        max_hp: f.combatant.health.max,
                        resource: resource_at(&f.caster, now),
                        statuses: f.combatant.statuses.iter().map(|s| s.kind.clone()).collect(),
                        kills: f.combatant.kills,
                        deaths: f.combatant.deaths,
                        down: self.respawns.is_down(&f.player.to_string()),
                    }
                })
                .collect(),
            projectiles: self
                .projectiles
                .iter()
                .map(|p| Shot {
                    ability: p.ability_id.clone(),
                    caster: p.caster_id.parse().unwrap_or(0),
                    x: f64::from(p.x),
                    y: f64::from(p.z),
                })
                .collect(),
            areas: self
                .areas
                .iter()
                .map(|a| Blast {
                    ability: a.ability_id.clone(),
                    caster: a.caster_id.parse().unwrap_or(0),
                    x: f64::from(a.x),
                    y: f64::from(a.z),
                    radius: f64::from(a.radius),
                    at: a.detonate_at_ms,
                })
                .collect(),
            kill_target: self.config.kill_target,
            ends_at: self.ends_at,
            winner: self.winner,
        }
    }

    fn event(&mut self, kind: &str, extra: Value) {
        let mut e = json!({ "type": kind });
        if let (Some(e), Some(x)) = (e.as_object_mut(), extra.as_object()) {
            e.extend(x.clone());
        }
        self.events.push(e);
        self.dirty = true;
    }

    fn index(&self, player: u64) -> Result<usize> {
        self.fighters.iter().position(|f| f.player == player).ok_or_else(|| kit::error(codes::NOT_MEMBER, "join the arena first"))
    }

    fn rules(&self, class: &str) -> Rules {
        let speed = self.config.classes.iter().find(|c| c.id == class).map_or(6.0, |c| c.speed);
        Rules { max_speed: speed, teleport: self.config.teleport, bounds: Some(self.bounds()), grace: 1.25 }
    }

    /// `(min_x, min_y, max_x, max_y)` in world metres.
    fn bounds(&self) -> (f64, f64, f64, f64) {
        let (x, y) = self.config.origin;
        (x, y, x + self.config.width, y + self.config.depth)
    }

    /// The `n`th spawn in world metres.
    fn spawn_at(&self, n: usize) -> (f64, f64) {
        let (dx, dy) = self.config.spawns.get(n % self.config.spawns.len().max(1)).copied().unwrap_or((0.0, 0.0));
        (self.config.origin.0 + dx, self.config.origin.1 + dy)
    }

    /// Takes the fighter out of the fight with their record.
    fn bench(&mut self, i: usize, removed: bool, target_until: u64) {
        let fighter = self.fighters.remove(i);
        let down = self.respawns.kills.remove(&fighter.player.to_string());
        self.bench.push(Benched { fighter, down, removed, target_until });
        let newest = self.bench.len() - 1;
        if newest >= self.config.players_max * BENCH_PER_SLOT
            && let Some(oldest) = self.bench[..newest].iter().position(|b| !b.removed)
        {
            self.bench.remove(oldest);
        }
        self.dirty = true;
    }

    /// A fighter in the fight, or one who left a moment ago and is still somewhere in the arena
    /// to be hit.
    fn target_mut(&mut self, player: u64, now: u64) -> Option<&mut Fighter> {
        if let Some(i) = self.fighters.iter().position(|f| f.player == player) {
            return Some(&mut self.fighters[i]);
        }
        self.bench.iter_mut().find(|b| b.open(now) && b.fighter.player == player).map(|b| &mut b.fighter)
    }

    /// Everyone who can be hit with where they are and whether they are down.
    fn targets(&self, now: u64) -> Vec<(u64, (f64, f64), bool)> {
        let fighting = self.fighters.iter().map(|f| (f.player, f.at(), self.respawns.is_down(&f.player.to_string())));
        let benched = self.bench.iter().filter(|b| b.open(now)).map(|b| (b.fighter.player, b.fighter.at(), b.down.is_some()));
        fighting.chain(benched).collect()
    }

    pub fn join(&mut self, player: u64, class: &str, now: u64) -> Result<()> {
        let Some(c) = self.config.classes.iter().find(|c| c.id == class).cloned() else {
            let names: Vec<&str> = self.config.classes.iter().map(|c| c.id.as_str()).collect();
            return Err(kit::error(codes::BAD_REQUEST, format!("a class is one of {}", names.join(", "))));
        };
        if let Some(b) = self.bench.iter().position(|b| b.fighter.player == player) {
            if self.bench[b].removed {
                return Err(kit::error(codes::FORBIDDEN, "removed for movement: back at the next start"));
            }
            if self.phase == Phase::Running {
                return self.rejoin(b, &c.id, now);
            }
            self.bench.remove(b);
        }
        if let Ok(i) = self.index(player) {
            if self.phase == Phase::Running {
                return Err(kit::error(codes::STARTED, "classes are picked before the fight"));
            }
            self.fighters[i].class = c.id;
            self.fighters[i].combatant = Combatant::new(c.max_hp);
            self.dirty = true;
            return Ok(());
        }
        if self.fighters.len() >= self.config.players_max {
            return Err(kit::error(codes::FULL, "the arena is full"));
        }
        let spawn = self.spawn_at(self.fighters.len());
        self.fighters.push(Fighter {
            player,
            class: c.id,
            combatant: Combatant::new(c.max_hp),
            caster: CasterBook::default(),
            warden: Warden::at(spawn, now),
            spawn,
            moved_at: now,
        });
        self.dirty = true;
        Ok(())
    }

    /// A benched fighter back in the running fight, as they were where they stood.
    fn rejoin(&mut self, b: usize, class: &str, now: u64) -> Result<()> {
        if self.bench[b].fighter.class != class {
            return Err(kit::error(codes::STARTED, "classes are picked before the fight"));
        }
        if self.fighters.len() >= self.config.players_max {
            return Err(kit::error(codes::FULL, "the arena is full"));
        }
        let Benched { mut fighter, down, .. } = self.bench.remove(b);
        fighter.warden.place(fighter.at(), now);
        fighter.moved_at = now;
        if let Some(record) = down {
            self.respawns.kills.insert(fighter.player.to_string(), record);
        }
        self.fighters.push(fighter);
        self.dirty = true;
        Ok(())
    }

    pub fn leave(&mut self, player: u64, now: u64) -> Result<()> {
        let i = self.index(player)?;
        if self.phase == Phase::Running {
            self.bench(i, false, now + self.config.respawn_ms);
            return Ok(());
        }
        self.fighters.remove(i);
        self.respawns.kills.remove(&player.to_string());
        self.dirty = true;
        Ok(())
    }

    pub fn start(&mut self, now: u64) -> Result<()> {
        if self.phase == Phase::Running {
            return Err(kit::error(codes::STARTED, "the fight is on"));
        }
        if self.fighters.len() < 2 {
            return Err(kit::error(codes::NOT_READY, "a fight takes two"));
        }
        self.phase = Phase::Running;
        self.ends_at = Some(now + self.config.duration_ms);
        self.winner = None;
        self.projectiles.clear();
        self.areas.clear();
        self.bench.clear();
        self.respawns = RespawnBook::default();
        let classes = self.config.classes.clone();
        for f in &mut self.fighters {
            let max = classes.iter().find(|c| c.id == f.class).map_or(100, |c| c.max_hp);
            f.combatant = Combatant::new(max);
            f.caster = CasterBook::default();
            f.warden = Warden::at(f.spawn, now);
            f.moved_at = now;
        }
        self.dirty = true;
        Ok(())
    }

    fn standing(&self, i: usize) -> Result<()> {
        if self.phase != Phase::Running {
            return Err(kit::error(codes::NOT_READY, "the fight has not started"));
        }
        if self.respawns.is_down(&self.fighters[i].player.to_string()) {
            return Err(kit::error(codes::CONFLICT, "you are down"));
        }
        Ok(())
    }

    /// A reported position in world metres: the warden keeps what the class allows. Returns the
    /// position kept.
    pub fn moved(&mut self, player: u64, to: (f64, f64), now: u64) -> Result<(f64, f64)> {
        if !finite(to) {
            return Err(kit::error(codes::BAD_REQUEST, "a position is a number of metres"));
        }
        let i = self.index(player)?;
        self.standing(i)?;
        self.fighters[i].moved_at = now;
        let rules = self.rules(&self.fighters[i].class);
        let verdict = self.fighters[i].warden.check(&rules, to, now);
        if let Some(v) = verdict.violation {
            self.event("violation", json!({ "player": player, "what": v.kind.as_str(), "detail": v.detail }));
            let limit = self.config.remove_after_strikes;
            if limit > 0 && self.fighters[i].warden.strikes(now) >= limit {
                self.bench(i, true, 0);
                self.event("removed", json!({ "player": player, "why": "movement" }));
                return Err(kit::error(codes::FORBIDDEN, "removed for movement the warden refused"));
            }
        }
        self.dirty = true;
        Ok(verdict.at)
    }

    /// A cast aimed at `aim`, a world position in metres. Returns whether it hit someone at once
    /// (a hit-scan strike).
    pub fn cast(&mut self, player: u64, ability_id: &str, aim: (f64, f64), now: u64) -> Result<bool> {
        if !finite(aim) {
            return Err(kit::error(codes::BAD_REQUEST, "an aim is a position in metres"));
        }
        let i = self.index(player)?;
        self.standing(i)?;
        let class = self.fighters[i].class.clone();
        let Some(ability) = self
            .config
            .classes
            .iter()
            .find(|c| c.id == class)
            .and_then(|c| c.abilities.iter().find(|a| a.spec.ability_id == ability_id))
            .cloned()
        else {
            return Err(kit::error(codes::NOT_FOUND, format!("a {class} has no ability `{ability_id}`")));
        };
        let from = self.fighters[i].at();
        let to_f32 = |p: (f64, f64)| (p.0 as f32, p.1 as f32);
        let cast = validate_cast(&ability.spec, &mut self.fighters[i].caster, to_f32(from), to_f32(aim), now).map_err(|why| match why {
            "ability on cooldown" => kit::error(codes::COOLDOWN, why),
            "not enough resource" => kit::error(codes::INSUFFICIENT, why),
            _ => kit::error(codes::OUT_OF_REACH, why),
        })?;
        self.event("cast", json!({ "ability": ability_id, "caster": player, "x": aim.0, "y": aim.1 }));
        match ability.spec.kind {
            AbilityKind::Instant { damage } => {
                let victim = self
                    .fighters
                    .iter()
                    .enumerate()
                    .filter(|(j, f)| {
                        *j != i
                            && !self.respawns.is_down(&f.player.to_string())
                            && dist(f.at(), aim) <= AIM_RADIUS
                            && dist(f.at(), from) <= f64::from(ability.spec.range)
                    })
                    .min_by(|a, b| dist(a.1.at(), aim).total_cmp(&dist(b.1.at(), aim)))
                    .map(|(_, f)| f.player);
                if let Some(victim) = victim {
                    self.damage(player, victim, ability_id, damage, ability.status.as_ref(), now);
                    return Ok(true);
                }
                Ok(false)
            }
            AbilityKind::Projectile { .. } => {
                self.projectiles.extend(Projectile::launch(&ability.spec, &player.to_string(), to_f32(from), &cast, now));
                Ok(false)
            }
            AbilityKind::Aoe { .. } => {
                self.areas.extend(PendingAoe::from_cast(&ability.spec, &player.to_string(), &cast, now));
                Ok(false)
            }
        }
    }

    fn damage(&mut self, caster: u64, victim: u64, ability_id: &str, amount: i64, status: Option<&Affliction>, now: u64) {
        let Some(f) = self.target_mut(victim, now) else { return };
        let outcome = f.combatant.hit(amount);
        if let Some(s) = status.filter(|_| !outcome.killed) {
            f.combatant.afflict(&s.kind, s.per_tick, s.every_ms, s.duration_ms, Some(caster.to_string()), now);
        }
        self.event("impact", json!({ "ability": ability_id, "caster": caster, "victim": victim, "damage": outcome.dealt }));
        if outcome.killed {
            self.killed(caster, victim, now);
        }
    }

    fn killed(&mut self, killer: u64, victim: u64, now: u64) {
        if killer != victim
            && let Some(k) = self.target_mut(killer, now)
        {
            k.combatant.kills += 1;
        }
        if self.fighters.iter().any(|f| f.player == victim) {
            self.respawns.record_kill(&victim.to_string(), &killer.to_string(), now, self.config.respawn_ms);
        } else if let Some(b) = self.bench.iter_mut().find(|b| b.fighter.player == victim) {
            b.down = Some(KillRecord { killer: killer.to_string(), at_ms: now, respawn_at_ms: now + self.config.respawn_ms });
        }
        self.event("kill", json!({ "killer": killer, "victim": victim }));
    }

    /// One tick: projectiles, areas, statuses, respawns, idle fighters, the end. Returns whether
    /// it ran.
    pub fn tick(&mut self, now: u64) -> bool {
        if self.phase != Phase::Running {
            return false;
        }
        self.ticks += 1;
        let mut shots = std::mem::take(&mut self.projectiles);
        let positions = self.targets(now);
        let mut hits = Vec::new();
        let (x0, y0, x1, y1) = self.bounds();
        shots.retain_mut(|p| {
            let caster: u64 = p.caster_id.parse().unwrap_or(0);
            let mut hit_test = |x: f32, y: f32, r: f32| {
                positions
                    .iter()
                    .filter(|(id, _, down)| *id != caster && !down)
                    .find(|(_, at, _)| dist(*at, (f64::from(x), f64::from(y))) <= f64::from(r))
                    .map(|(id, _, _)| id.to_string())
            };
            let mut blocked = |x: f32, y: f32| f64::from(x) < x0 || f64::from(y) < y0 || f64::from(x) > x1 || f64::from(y) > y1;
            match p.step(TICK_MS, &mut hit_test, &mut blocked) {
                ProjectileStep::Flying => true,
                ProjectileStep::Hit { target_id } => {
                    hits.push((p.caster_id.clone(), target_id, p.ability_id.clone(), p.damage));
                    false
                }
                ProjectileStep::Expired => false,
            }
        });
        self.projectiles = shots;
        if !self.projectiles.is_empty() || !hits.is_empty() {
            self.dirty = true;
        }
        for (caster, target, ability_id, damage) in hits {
            if let (Ok(caster), Ok(target)) = (caster.parse::<u64>(), target.parse::<u64>()) {
                let status = self.status_of(&ability_id);
                self.damage(caster, target, &ability_id, damage, status.as_ref(), now);
            }
        }
        let (ready, waiting): (Vec<PendingAoe>, Vec<PendingAoe>) = std::mem::take(&mut self.areas).into_iter().partition(|a| a.ready(now));
        self.areas = waiting;
        for blast in ready {
            let victims: Vec<(String, (f32, f32))> = self
                .targets(now)
                .into_iter()
                .filter(|(_, _, down)| !down)
                .map(|(id, at, _)| (id.to_string(), (at.0 as f32, at.1 as f32)))
                .collect();
            let caster: u64 = blast.caster_id.parse().unwrap_or(0);
            let status = self.status_of(&blast.ability_id);
            for (id, damage) in blast.resolve(&victims) {
                if let Ok(victim) = id.parse::<u64>() {
                    self.damage(caster, victim, &blast.ability_id, damage, status.as_ref(), now);
                }
            }
            self.dirty = true;
        }
        for i in 0..self.fighters.len() {
            let player = self.fighters[i].player;
            for effect in self.fighters[i].combatant.tick(now) {
                self.dirty = true;
                if effect.outcome.killed {
                    let killer = effect.source.as_deref().and_then(|s| s.parse().ok()).unwrap_or(player);
                    self.killed(killer, player, now);
                }
            }
        }
        for i in 0..self.bench.len() {
            if !self.bench[i].open(now) {
                continue;
            }
            let player = self.bench[i].fighter.player;
            for effect in self.bench[i].fighter.combatant.tick(now) {
                self.dirty = true;
                if effect.outcome.killed {
                    let killer = effect.source.as_deref().and_then(|s| s.parse().ok()).unwrap_or(player);
                    self.killed(killer, player, now);
                }
            }
        }
        for id in self.respawns.due(now) {
            if let Some(f) = self.fighters.iter_mut().find(|f| f.player.to_string() == id) {
                f.combatant.health.revive();
                f.combatant.statuses.clear();
                f.warden.place(f.spawn, now);
                f.moved_at = now;
                let player = f.player;
                self.event("respawn", json!({ "player": player }));
            }
        }
        self.bench_the_idle(now);
        let leader = self.fighters.iter().max_by_key(|f| f.combatant.kills).map(|f| (f.player, f.combatant.kills));
        let tied = leader.is_some_and(|(p, k)| self.fighters.iter().any(|f| f.player != p && f.combatant.kills == k));
        let reached = leader.is_some_and(|(_, k)| k >= self.config.kill_target);
        if reached || self.ends_at.is_some_and(|t| now >= t) {
            self.phase = Phase::Finished;
            self.winner = leader.filter(|_| reached || !tied).map(|(p, _)| p);
            self.event("finished", json!({ "winner": self.winner }));
        }
        true
    }

    /// Benches the fighters who are up and have sent no `move` for `idle_ms`.
    fn bench_the_idle(&mut self, now: u64) {
        let idle_ms = self.config.idle_ms;
        if idle_ms == 0 {
            return;
        }
        let idle: Vec<usize> = (0..self.fighters.len())
            .rev()
            .filter(|&i| {
                let f = &self.fighters[i];
                now.saturating_sub(f.moved_at) >= idle_ms && !self.respawns.is_down(&f.player.to_string())
            })
            .collect();
        for i in idle {
            let player = self.fighters[i].player;
            self.bench(i, false, 0);
            self.event("removed", json!({ "player": player, "why": "idle" }));
        }
    }

    fn status_of(&self, ability_id: &str) -> Option<Affliction> {
        self.config.classes.iter().flat_map(|c| &c.abilities).find(|a| a.spec.ability_id == ability_id).and_then(|a| a.status.clone())
    }
}

/// The hub: the arena, and what the kit protocol keeps beside it.
#[derive(Serialize, Deserialize, Default, Debug)]
pub struct ArenaHub {
    #[serde(flatten)]
    pub arena: Arena,
    #[serde(default)]
    pub kit: Publisher,
    #[serde(default)]
    pub receipts: Receipts,
}

impl ArenaHub {
    fn act(&mut self, ctx: &Ctx, call: &Call<'_>, now: u64) -> Result<Vec<u8>> {
        let a = &mut self.arena;
        let out = match call.method {
            "join" => {
                let j: Join = kit::args(call)?;
                a.join(call.player()?, &j.class, now)?;
                encode(&true)
            }
            "leave" => {
                a.leave(call.player()?, now)?;
                encode(&true)
            }
            "start" => {
                let allowed = match call.caller {
                    Caller::Developer(_) => true,
                    Caller::Player(p) => a.fighters.first().map(|f| f.player) == Some(p),
                    _ => false,
                };
                if !allowed {
                    return Err(kit::error(codes::FORBIDDEN, "the first to join, or a developer, starts it"));
                }
                a.start(now)?;
                ctx.timer_every("tick", TICK_MS)?;
                encode(&true)
            }
            "move" => {
                let m: Move = kit::args(call)?;
                let kept = a.moved(call.player()?, (m.x, m.y), now);
                self.flush(ctx, false, now)?;
                let (x, y) = kept?;
                return encode(&Kept { x, y });
            }
            "cast" => {
                let c: Cast = kit::args(call)?;
                encode(&a.cast(call.player()?, &c.ability, (c.x, c.y), now)?)
            }
            other => return Err(Error::unknown_method(other)),
        };
        self.flush(ctx, true, now)?;
        out
    }

    /// Publishes the events since the last time, and the arena when `snapshot` says so.
    fn flush(&mut self, ctx: &Ctx, snapshot: bool, now: u64) -> Result<()> {
        let events = std::mem::take(&mut self.arena.events);
        for e in &events {
            self.kit.event(ctx, TOPIC, e)?;
            self.realtime(ctx, e);
        }
        if snapshot {
            self.arena.dirty = false;
            self.kit.snapshot(ctx, TOPIC, &self.arena.view(now))?;
        }
        Ok(())
    }

    /// Casts, impacts and the warden's flags as realtime events, when the arena is realtime.
    fn realtime(&self, ctx: &Ctx, e: &Value) {
        if !self.arena.config.realtime {
            return;
        }
        let at = self.arena.config.centre_chunk();
        let actor = actor_id(&format!("arena:{}", ctx.key));
        let id = |k: &str| e[k].as_u64().map(|v| v.to_string());
        let sent = match e["type"].as_str() {
            Some(kind @ ("cast" | "impact")) => {
                let body = wire::AbilityUse {
                    kind: kind.into(),
                    ability_id: e["ability"].as_str().unwrap_or_default().into(),
                    caster_id: id("caster").unwrap_or_default(),
                    victim_id: id("victim"),
                    damage: e["damage"].as_i64().unwrap_or(0),
                };
                wire::emit_event(ctx, at, EVENT_DISTANCE, &actor, wire::ABILITY, &body)
            }
            Some("violation") => {
                let body = wire::MovementViolation {
                    kind: e["what"].as_str().unwrap_or_default().into(),
                    user_id: id("player").unwrap_or_default(),
                    detail: e["detail"].as_str().unwrap_or_default().into(),
                };
                wire::emit_event(ctx, at, EVENT_DISTANCE, &actor, wire::MOVEMENT_VIOLATION, &body)
            }
            _ => Ok(()),
        };
        if let Err(Error(why)) = sent {
            ctx.log(Level::Warn, &format!("a realtime event did not go out: {why}"));
        }
    }
}

impl Hub for ArenaHub {
    fn spawn(_ctx: &Ctx, seed: &[u8]) -> Result<Self> {
        let mut hub = Self::default();
        if !seed.is_empty() {
            hub.arena.config = serde_json::from_slice(seed).map_err(|e| Error::new(format!("seed is not a JSON config: {e}")))?;
        }
        Ok(hub)
    }

    fn load(ctx: &Ctx, snapshot: &[u8], _from_version: u64) -> Result<Self> {
        let mut hub: Self = decode(snapshot)?;
        let now = ctx.now_ms();
        for f in &mut hub.arena.fighters {
            f.moved_at = now;
        }
        Ok(hub)
    }

    fn persist(&mut self, _ctx: &Ctx) -> Result<Vec<u8>> {
        encode(self)
    }

    fn handle(&mut self, ctx: &Ctx, call: Call<'_>) -> Result<Vec<u8>> {
        let now = ctx.now_ms();
        match call.method {
            "state" => encode(&self.arena.view(now)),
            kit::SNAPSHOT_METHOD => self.kit.snapshot_reply(ctx, TOPIC, &self.arena.view(now)),
            _ => Receipts::run(self, |h| &mut h.receipts, &call, now, |h| h.act(ctx, &call, now)),
        }
    }

    fn on_timer(&mut self, ctx: &Ctx, timer: &str) -> Result<()> {
        if timer != "tick" {
            return Ok(());
        }
        let now = ctx.now_ms();
        if !self.arena.tick(now) {
            ctx.cancel_timer("tick");
            return Ok(());
        }
        let ended = self.arena.phase != Phase::Running;
        if ended {
            ctx.cancel_timer("tick");
            ctx.persist_now();
        }
        let due = self.arena.dirty && (ended || self.arena.ticks.is_multiple_of(PUBLISH_EVERY));
        self.flush(ctx, due, now)
    }
}

