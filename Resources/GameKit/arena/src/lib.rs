pub const TOPIC: &str = "arena";
pub const TICK_MS: u64 = 100;
/// Ticks between snapshots while nothing else publishes.
const PUBLISH_EVERY: u64 = 2;
/// How near its aim a hit-scan strike finds its victim.
const AIM_RADIUS: f64 = 1.5;
const EVENT_DISTANCE: u8 = 3;
/// Metres along one side of a chunk.
const CHUNK_M: f64 = 16.0;
/// The most travel a fighter banks: this many seconds at full speed, and this many metres more.
const BANK_S: f64 = 1.0;
const BANK_M: f64 = 0.5;
/// A speed cut of at most this many metres is jitter and costs no strike.
const JITTER_M: f64 = 1.0;
/// Benched fighters kept for each place in the arena.
const BENCH_PER_SLOT: usize = 4;

