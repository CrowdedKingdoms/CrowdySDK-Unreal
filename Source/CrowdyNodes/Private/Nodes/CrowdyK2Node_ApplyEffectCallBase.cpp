FText UCrowdyK2Node_ApplyEffectCallBase::GetNodeTitle(ENodeTitleType::Type TitleType) const
{
	if (const UCrowdyEffect* Effect = GetLiteralEffect())
	{
		return FText::Format(LOCTEXT("NodeTitleWithEffect", "{0}: {1}"),
			GetBaseNodeTitle(), FText::FromString(Effect->GetName()));
	}
	return GetBaseNodeTitle();
}

