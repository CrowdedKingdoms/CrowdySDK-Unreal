UCrowdyEffect* UCrowdyK2Node_ApplyEffectCallBase::GetLiteralEffect() const
{
	// Mid-rebuild, the live Effect pin is a freshly allocated one with no value yet (the value is only copied back
	// off the outgoing pin once pin allocation has returned), so the pending value captured in
	// ReallocatePinsDuringReconstruction is the only correct source of truth at that point.
	UCrowdyEffect* Effect = PendingReconstructionEffect;
	if (!Effect)
	{
		const UEdGraphPin* Pin = FindPin(PN_Effect, EGPD_Input);
		if (!Pin || Pin->LinkedTo.Num() > 0)
		{
			return nullptr;
		}
		Effect = Cast<UCrowdyEffect>(Pin->DefaultObject);
	}

	// Everything this node shapes itself from lives on the asset, and the asset can still be an unserialized export
	// while this graph is compiled on load, so no caller may read it before it is in.
	PreloadEffectAsset(Effect);
	return Effect;
}

void UCrowdyK2Node_ApplyEffectCallBase::ReallocatePinsDuringReconstruction(TArray<UEdGraphPin*>& OldPins)
{
	// Pin allocation (run by Super below) rebuilds a brand new Effect pin with an empty DefaultObject, and the
	// outgoing pin's value is only copied onto it afterward. Read that value now, off the still intact OldPins, so
	// the reshape sees the effect that is actually about to be restored instead of treating the node as emptied out.
	PendingReconstructionEffect = nullptr;
	for (UEdGraphPin* OldPin : OldPins)
	{
		if (OldPin && OldPin->PinName == PN_Effect && OldPin->LinkedTo.Num() == 0)
		{
			PendingReconstructionEffect = Cast<UCrowdyEffect>(OldPin->DefaultObject);
			break;
		}
	}

	Super::ReallocatePinsDuringReconstruction(OldPins);

	PendingReconstructionEffect = nullptr;
}

void UCrowdyK2Node_ApplyEffectCallBase::AllocateDefaultPins()
{
	// A node placed from the Blueprint action menu is handed its function reference before its pins are built. One
	// created any other way still needs it, since every pin here comes from that function's signature.
	if (FunctionReference.GetMemberName().IsNone())
	{
		if (UFunction* Wrapped = GetWrappedFunction())
		{
			SetFromFunction(Wrapped);
		}
	}

	Super::AllocateDefaultPins();
	SynchronizeEffectPins();
	RegisterEffectAssetListener();
}

void UCrowdyK2Node_ApplyEffectCallBase::PostReconstructNode()
{
	Super::PostReconstructNode();

	// A rebuild carries a designer-set value from the old pin onto the new one, hidden or not. Re-hiding here, after
	// that copy has happened, is what stops a Source or Level the effect no longer uses from reaching the call.
	ApplyParameterPinVisibility();
}

void UCrowdyK2Node_ApplyEffectCallBase::ApplyParameterPinVisibility()
{
	UCrowdyEffect* Effect = GetLiteralEffect();
	const bool bHasLiteralEffect = Effect != nullptr;
	const FCrowdyApplyEffectPinPlan Plan = CrowdyApplyEffectNodePins::BuildPinPlan(Effect);

	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();

	for (UEdGraphPin* Pin : Pins)
	{
		if (!Pin || Pin->Direction != EGPD_Input)
		{
			continue;
		}
		if (ActionForParameterPin(Pin->PinName, Plan, bHasLiteralEffect) != EParameterPinAction::HideAndReset)
		{
			continue;
		}

		Pin->bHidden = true;
		if (Schema)
		{
			Schema->ResetPinToAutogeneratedDefaultValue(Pin, false);
		}
	}
}

void UCrowdyK2Node_ApplyEffectCallBase::SynchronizeEffectPins()
{
	ApplyParameterPinVisibility();

	UCrowdyEffect* Effect = GetLiteralEffect();
	if (!Effect)
	{
		// No literal effect: leave the plain pin set, with the raw Overrides map visible. ExpandNode and
		// ValidateNodeDuringCompilation detect this same state and degrade accordingly.
		return;
	}

	const FCrowdyApplyEffectPinPlan Plan = CrowdyApplyEffectNodePins::BuildPinPlan(Effect);
	const UEdGraphSchema_K2* Schema = GetDefault<UEdGraphSchema_K2>();

	for (const FCrowdyApplyEffectPinEntry& Entry : Plan.Magnitudes)
	{
		UEdGraphPin* Pin = CreatePin(EGPD_Input, MagnitudePinType(Entry.ValueType), Entry.PinName);
		Pin->PinFriendlyName = FText::FromString(Entry.MagnitudeName);
		CrowdyApplyEffectNodePins::ApplyMagnitudeDefaultToPin(Pin, Entry, Schema);
	}
}

void UCrowdyK2Node_ApplyEffectCallBase::RemoveMagnitudePins()
{
	TArray<UEdGraphPin*> MagnitudePins;
	for (UEdGraphPin* Pin : Pins)
	{
		if (Pin && ShouldRemovePinBeforeCall(Pin->PinName))
		{
			MagnitudePins.Add(Pin);
		}
	}
	for (UEdGraphPin* Pin : MagnitudePins)
	{
		RemovePin(Pin);
	}
}

void UCrowdyK2Node_ApplyEffectCallBase::PinDefaultValueChanged(UEdGraphPin* Pin)
{
	Super::PinDefaultValueChanged(Pin);

	// A new effect asset reshapes the whole magnitude pin set. Rebuilding here would tear down this pin set
	// immediately, but the caller that set the value keeps dereferencing the changed pin after this returns, so
	// freeing it now is a use-after-free. Defer the rebuild until that call has fully unwound.
	if (Pin && Pin->PinName == PN_Effect)
	{
		ScheduleReconstruct();
	}
}

void UCrowdyK2Node_ApplyEffectCallBase::ScheduleReconstruct()
{
	if (bReconstructPending || !GEditor)
	{
		return;
	}
	bReconstructPending = true;

	// A next-tick timer runs once the current input event has fully unwound, so the pin the picker still holds is no
	// longer live when the rebuild destroys it. Weak-bound: a node deleted before the tick fires does nothing.
	GEditor->GetTimerManager()->SetTimerForNextTick(FTimerDelegate::CreateWeakLambda(this, [this]()
	{
		bReconstructPending = false;
		ReconstructNode();
		if (UBlueprint* Blueprint = FBlueprintEditorUtils::FindBlueprintForNode(this))
		{
			FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
		}
	}));
}

void UCrowdyK2Node_ApplyEffectCallBase::PinConnectionListChanged(UEdGraphPin* Pin)
{
	Super::PinConnectionListChanged(Pin);

	// Wiring or unwiring the Effect pin flips between the typed and the plain pin sets.
	if (Pin && Pin->PinName == PN_Effect)
	{
		ReconstructNode();
	}
}

void UCrowdyK2Node_ApplyEffectCallBase::PostPlacedNewNode()
{
	Super::PostPlacedNewNode();
	RegisterEffectAssetListener();
}

void UCrowdyK2Node_ApplyEffectCallBase::PostLoad()
{
	Super::PostLoad();
	RegisterEffectAssetListener();
}

void UCrowdyK2Node_ApplyEffectCallBase::BeginDestroy()
{
	if (OnPropertyChangedHandle.IsValid())
	{
		FCoreUObjectDelegates::OnObjectPropertyChanged.Remove(OnPropertyChangedHandle);
		OnPropertyChangedHandle.Reset();
	}
	Super::BeginDestroy();
}

void UCrowdyK2Node_ApplyEffectCallBase::RegisterEffectAssetListener()
{
	// Only real graph nodes need to react to asset edits; template nodes built for the action menu have no graph and
	// would only add a needless global-delegate subscription.
	if (!GetGraph())
	{
		return;
	}
	if (!OnPropertyChangedHandle.IsValid())
	{
		OnPropertyChangedHandle = FCoreUObjectDelegates::OnObjectPropertyChanged.AddUObject(
			this, &UCrowdyK2Node_ApplyEffectCallBase::HandleObjectPropertyChanged);
	}
}

void UCrowdyK2Node_ApplyEffectCallBase::HandleObjectPropertyChanged(UObject* Object,
	FPropertyChangedEvent& PropertyChangedEvent)
{
	// React only to edits on the effect this node references; any other asset's change is irrelevant.
	if (!Object || Object != GetLiteralEffect())
	{
		return;
	}

	// A slider drag fires a stream of interactive changes; skip them and rebuild once when the final committed
	// change lands, so mid-drag churn does not thrash the whole node.
	if (PropertyChangedEvent.ChangeType == EPropertyChangeType::Interactive)
	{
		return;
	}

	// Only an edit to a field the pin layout is built from needs a rebuild.
	if (!ChangeAffectsPinPlan(PropertyChangedEvent))
	{
		return;
	}

	ReconstructNode();
}

